// Catalog build: catalog/<source>/<name>/meta.json -> src/catalog/metas.generated.mjs + registry.generated.tsx.
// Project prepare: copies the HyperFrames / Lottie / clip files a storyboard needs into work/fm-assets/ and writes
// src/catalog/user.generated.tsx so your own .tsx scenes are bundled with the kit.
// (Same build as connect-ai-video-motion; this one sorts items by role: scene, bg, transition, sweep.)
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {KIT} from './project.mjs';
import {validateMeta, kindOf, mediaOf} from '../src/core/catalog.mjs';
import {assetName, mediaName} from '../src/core/assets.mjs';

const require = createRequire(import.meta.url);
const CAT = path.join(KIT, 'catalog');
const GEN = path.join(KIT, 'src', 'catalog');
const COMPONENT_FILES = ['index.tsx', 'index.jsx', 'index.ts'];

export function scanCatalog() {
  const metas = {}, errors = [], dirs = {};
  if (!fs.existsSync(CAT)) return {metas, errors, dirs};
  for (const src of fs.readdirSync(CAT).sort()) {
    const sd = path.join(CAT, src);
    if (!fs.statSync(sd).isDirectory()) continue;
    for (const name of fs.readdirSync(sd).sort()) {
      const d = path.join(sd, name);
      const mf = path.join(d, 'meta.json');
      if (!fs.existsSync(mf)) continue;
      let m;
      try {
        m = JSON.parse(fs.readFileSync(mf, 'utf8'));
      } catch (e) {
        errors.push(`${src}/${name}/meta.json: not valid JSON (${e.message})`);
        continue;
      }
      const errs = validateMeta(m, name);
      const comp = COMPONENT_FILES.find((f) => fs.existsSync(path.join(d, f)));
      const t = m.source?.type;
      const ok = !m.status || m.status === 'ok';
      if ((t === 'hyperframes' || t === 'lottie') && ok && !comp) {
        if (!m.src || !fs.existsSync(path.join(d, m.src))) errs.push(`"src" file ${m.src || '(none)'} is missing`);
      } else if (!comp && ok) errs.push('index.tsx is missing');
      if (metas[m.kind]) errs.push(`kind "${m.kind}" is used twice`);
      for (const e of errs) errors.push(`${src}/${name}: ${e}`);
      if (errs.length) continue;
      metas[m.kind] = {...m, dir: `catalog/${src}/${name}`, component: comp || null};
      dirs[m.kind] = d;
    }
  }
  return {metas, errors, dirs};
}

export function buildCatalog({log = () => {}} = {}) {
  const {metas, errors} = scanCatalog();
  fs.mkdirSync(GEN, {recursive: true});
  const lines = Object.values(metas).sort((a, b) => (a.kind < b.kind ? -1 : 1));
  const metaJs = `// generated by lib/catalog-build.mjs from catalog/*/*/meta.json. Do not edit; run the catalog command.\nexport const METAS = ${JSON.stringify(Object.fromEntries(lines.map((m) => [m.kind, m])), null, 1)};\n`;
  writeIfChanged(path.join(GEN, 'metas.generated.mjs'), metaJs);
  const imports = [];
  const maps = {scene: [], bg: [], transition: [], sweep: []};
  lines.forEach((m, i) => {
    if (m.status && m.status !== 'ok') return;
    const t = m.source?.type;
    if (m.component) {
      imports.push(`import C${i} from '../../${m.dir}/${m.component.replace(/\.(tsx|jsx|ts)$/, '')}';`);
      maps[m.role].push(`  ${JSON.stringify(m.kind)}: C${i},`);
    } else if (t === 'hyperframes') maps[m.role].push(`  ${JSON.stringify(m.kind)}: HyperFramesBlock,`);
    else if (t === 'lottie') maps[m.role].push(`  ${JSON.stringify(m.kind)}: LottieFile,`);
  });
  const reg = `// generated by lib/catalog-build.mjs. Do not edit; run the catalog command.
import React from 'react';
import {HyperFramesBlock} from '../adapters/HyperFrames';
import {LottieFile} from '../adapters/Lottie';
${imports.join('\n')}

export const SCENES: Record<string, React.FC<any>> = {
${maps.scene.join('\n')}
};
export const BGS: Record<string, React.FC<any>> = {
${maps.bg.join('\n')}
};
// a transition item exports a function (W, H, line) => a @remotion/transitions presentation
export const TRANSITIONS: Record<string, (w: number, h: number, it: any) => any> = {
${maps.transition.join('\n')}
};
export const SWEEPS: Record<string, React.FC<any>> = {
${maps.sweep.join('\n')}
};
`;
  writeIfChanged(path.join(GEN, 'registry.generated.tsx'), reg);
  if (!fs.existsSync(path.join(GEN, 'user.generated.tsx'))) writeUser([]);
  log(`  catalog: ${lines.length} items${errors.length ? `, ${errors.length} problem(s)` : ''}`);
  return {metas, errors};
}

// GSAP plugin names a block loads from a CDN (same rule as src/adapters/HyperFrames.tsx gsapPluginsIn)
export function pluginsOf(file) {
  const html = fs.readFileSync(file, 'utf8'), out = [];
  for (const m of html.matchAll(/<script[^>]*src=["'][^"']*gsap[^"']*\/(?:dist\/)?([A-Za-z0-9]+)\.min\.js["']/gi)) if (m[1] !== 'gsap' && !out.includes(m[1])) out.push(m[1]);
  return out;
}

function writeIfChanged(f, text) {
  if (fs.existsSync(f) && fs.readFileSync(f, 'utf8') === text) return;
  fs.writeFileSync(f, text);
}

function writeUser(list) {
  const imports = list.map((x, i) => `import U${i} from ${JSON.stringify(x.abs.replace(/\\/g, '/').replace(/\.(tsx|jsx|ts|js)$/, ''))};`);
  const entries = list.map((x, i) => `  ${JSON.stringify(x.key)}: U${i},`);
  writeIfChanged(
    path.join(GEN, 'user.generated.tsx'),
    `// generated for your project by lib/catalog-build.mjs (your own scenes from storyboard.json). Do not edit.\nimport React from 'react';\n${imports.join('\n')}\n\nexport const USER: Record<string, React.FC<any>> = {\n${entries.join('\n')}\n};\n`,
  );
}

/**
 * Get a project ready to render: your own scenes bundled, HyperFrames / Lottie / clip files copied into work/fm-assets.
 * Returns {errors: [sentences], users: [{key, abs}], assets: [names]}.
 */
export function prepareProject(P, story, metas) {
  const errors = [], users = [], assets = new Set();
  const outDir = path.join(P.work, 'fm-assets');
  fs.mkdirSync(outDir, {recursive: true});
  const copy = (from, name) => {
    const to = path.join(outDir, name);
    if (!fs.existsSync(to) || fs.statSync(to).mtimeMs < fs.statSync(from).mtimeMs || fs.statSync(to).size !== fs.statSync(from).size) fs.copyFileSync(from, to);
    assets.add(name);
  };
  let needsGsap = false;
  const plugins = new Set();
  const lines = [];
  for (const b of story?.beats || []) {
    lines.push(b);
    for (const k of ['bg', 'in']) if (b[k] && typeof b[k] === 'object') lines.push(b[k]);
  }
  // your own font file for the whole film ("font": "input/MyFont.ttf"; .ttf .otf .woff .woff2)
  if (story?.font) {
    const abs = path.resolve(P.dir, String(story.font));
    if (!/\.(ttf|otf|woff2?)$/i.test(String(story.font))) errors.push(`font: ${story.font} is not a font file (.ttf, .otf, .woff, .woff2)`);
    else if (!fs.existsSync(abs)) errors.push(`font: ${story.font} not found (looked at ${abs}). Put the file you downloaded (Google Fonts: Get font, Download) in input/.`);
    else copy(abs, mediaName(String(story.font)));
  }
  for (const it of lines) {
    const kind = kindOf(it.kind);
    const m = metas[kind];
    const id = it.id || kind;
    if (kind === 'custom') {
      if (!it.component) { errors.push(`${id}: kind "custom" needs "component": "./path/To/Scene.tsx"`); continue; }
      const abs = path.resolve(P.dir, it.component);
      if (!fs.existsSync(abs)) { errors.push(`${id}: component ${it.component} not found (looked at ${abs})`); continue; }
      if (!users.some((u) => u.key === it.component)) users.push({key: it.component, abs});
      continue;
    }
    if (kind === 'hyperframes' || kind === 'lottie' || kind === 'clip') {
      if (!it.src) { errors.push(`${id}: kind "${kind}" needs "src": "./my-file.${kind === 'lottie' ? 'json' : kind === 'clip' ? 'mp4' : 'html'}"`); continue; }
      const abs = path.resolve(P.dir, it.src);
      if (!fs.existsSync(abs)) { errors.push(`${id}: ${it.src} not found`); continue; }
      copy(abs, assetName(kind, it.src));
      if (kind === 'hyperframes') { needsGsap = true; pluginsOf(abs).forEach((n) => plugins.add(n)); }
      continue;
    }
    // pictures, clips, models the scene shows: your file (from the project folder) or one that ships with the kit ("kit:...")
    for (const src of mediaOf(it, m)) {
      const abs = src.startsWith('kit:') ? path.join(KIT, src.slice(4)) : path.resolve(P.dir, src);
      if (!fs.existsSync(abs)) { errors.push(`${id}: ${src} not found${src.startsWith('kit:') ? ' in the kit' : ` (looked at ${abs})`}`); continue; }
      copy(abs, mediaName(src));
    }
    if (m && (m.source?.type === 'hyperframes' || m.source?.type === 'lottie') && m.src) {
      copy(path.join(KIT, m.dir, m.src), assetName(kind, m.src));
      if (m.source.type === 'hyperframes') { needsGsap = true; pluginsOf(path.join(KIT, m.dir, m.src)).forEach((n) => plugins.add(n)); }
      for (const extra of m.files || []) copy(path.join(KIT, m.dir, extra), assetName(kind, extra));
    }
  }
  if (needsGsap) {
    // HyperFrames blocks load GSAP from a CDN; we give them the copy that is installed with the kit instead
    try {
      const dist = path.join(path.dirname(require.resolve('gsap/package.json')), 'dist');
      copy(path.join(dist, 'gsap.min.js'), 'gsap.min.js');
      for (const n of plugins) {
        if (fs.existsSync(path.join(dist, n + '.min.js'))) copy(path.join(dist, n + '.min.js'), `gsap-${n}.min.js`);
        else errors.push(`a HyperFrames block loads the GSAP plugin ${n}, which is not in the installed gsap package`);
      }
    } catch {
      errors.push('HyperFrames blocks need the "gsap" package (npm install gsap)');
    }
  }
  writeUser(users);
  return {errors, users, assets: [...assets]};
}
